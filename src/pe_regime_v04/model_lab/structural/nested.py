def build_formal_nested_oof_plan(
    *,
    seed: int,
    outer_fold_id: str,
    candidate_id: str,
    base_model_id: str,
    authorization: StructuralExecutionAuthorization,
) -> NestedOOFPlan:
    """Reconstruct one entire exact fold from the sealed 1,800-row spent surface."""

    authorization.require_formal_spent_go()
    if not isinstance(outer_fold_id, str) or not outer_fold_id.startswith("fold_"):
        raise StructuralContractError("formal outer fold ID is invalid")
    try:
        fold_index = int(outer_fold_id.removeprefix("fold_"))
    except ValueError as exc:
        raise StructuralContractError("formal outer fold ID is invalid") from exc
    if outer_fold_id != f"fold_{fold_index:03d}" or fold_index not in range(
        FORMAL_OUTER_FOLD_COUNT
    ):
        raise StructuralContractError("formal outer fold is outside the exact 74-fold schedule")

    from ..models.wave1.artifacts import inspect_predict_seed_entry, load_predict_inputs

    manifest = load_predict_inputs(
        authorization.project_root / "outputs/model_zoo_wave1_screen_20260819/PREDICT_INPUTS.json"
    )
    entries = [row for row in manifest["seeds"] if int(row["seed"]) == seed]
    if len(entries) != 1:
        raise StructuralContractError("formal seed is outside the sealed spent universe")
    inspected = inspect_predict_seed_entry(entries[0])
    dates = pd.to_datetime(inspected["dates"], errors="raise")
    if len(dates) != FORMAL_SURFACE_ROWS:
        raise StructuralContractError("formal identity surface must contain exactly 1,800 rows")
    identity = pd.DataFrame(
        {"date": dates.to_numpy(copy=True), "session_position": np.arange(len(dates))}
    )
    folds = generate_pit_folds(identity, FORMAL_OUTER_FOLD_SPEC, date_column="date")
    position_payload = [
        {
            "fold_id": fold.fold_id,
            "train_positions": list(fold.train_positions),
            "test_positions": list(fold.test_positions),
        }
        for fold in folds
    ]
    coverage = [position for fold in folds for position in fold.test_positions]
    if (
        len(folds) != FORMAL_OUTER_FOLD_COUNT
        or tuple(fold.test_positions[0] for fold in folds) != FORMAL_OUTER_STARTS
        or len(folds[-1].test_positions) != 15
        or sha256_bytes(canonical_json_bytes(position_payload))
        != FORMAL_OUTER_POSITION_SCHEDULE_SHA256
        or sha256_bytes(canonical_json_bytes(coverage)) != FORMAL_OUTER_COVERAGE_SHA256
        or coverage != list(range(252, FORMAL_SURFACE_ROWS))
    ):
        raise StructuralContractError("formal outer schedule/coverage reconstruction changed")
    fold = folds[fold_index]
    if fold.fold_id != outer_fold_id:
        raise StructuralContractError("formal fold ID/member mapping changed")
    train = identity.iloc[list(fold.train_positions)].reset_index(drop=True)
    test = identity.iloc[list(fold.test_positions)].reset_index(drop=True)
    return _build_nested_oof_plan(
        train,
        test,
        seed=seed,
        outer_fold_id=fold.fold_id,
        outer_cutoff=fold.train_end,
        candidate_id=candidate_id,
        base_model_id=base_model_id,
        authorization=authorization,
        formal_schedule_sha256=FORMAL_OUTER_POSITION_SCHEDULE_SHA256,
        formal_surface_identity_sha256=logical_frame_sha256(identity),
        formal_fold_index=fold_index,
        formal_fold_count=FORMAL_OUTER_FOLD_COUNT,
    )
